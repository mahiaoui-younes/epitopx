def find_epitope_in_sequence(sequence: str, epitope: str):
    seq = sequence.upper().replace(" ", "")
    epi = epitope.upper().replace(" ", "")
    pos = seq.find(epi)
    if pos < 0:
        return (0, 0)
    return (pos + 1, pos + len(epi))


def overlap_fraction(ps, pe, ks, ke):
    if ks == 0 or ke == 0:
        return 0.0
    known = set(range(ks, ke + 1))
    pred = set(range(ps, pe + 1))
    if not known:
        return 0.0
    return len(known & pred) / len(known)


