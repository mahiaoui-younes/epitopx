def run_benchmark(verbose: bool = True):
    total_known = 0
    core_det = bio_det = 0
    core_t5 = bio_t5 = core_t10 = bio_t10 = 0
    protein_results = []
    missed_bio = []

    for idx, prot in enumerate(PROTEINS, 1):
        seq = prot.sequence.upper().replace("\n", "").replace(" ", "")

        if verbose:
            print("-" * 100)
            print(f"  [{idx:>3}] {prot.name} ({prot.accession})")
            print(f"       {prot.description}")
            print(f"       Sequence length: {len(seq)} aa  "
                  f"| Known epitopes: {len(prot.known_epitopes)}")

        # ---- Core ----
        core_scorer = GlobalScorer()
        core_res = core_scorer.get_residue_scores(seq)
        core_sel = EpitopeSelector()
        core_epi = core_sel.find_epitopes(seq, core_res)

        # ---- Bio ----
        bio_scorer = CombinedScorer()
        bio_res = bio_scorer.get_residue_results(seq)
        bio_det_obj = EpitopeDetector({"min_length": 8, "max_length": 25, "top_n": 30})
        bio_hits = bio_det_obj.detect(seq, bio_res)

        p_core = p_bio = p_c5 = p_b5 = 0

        for epi_seq in prot.known_epitopes:
            total_known += 1
            ks, ke = find_epitope_in_sequence(seq, epi_seq)
            if ks == 0:
                if verbose:
                    print(f"       WARNING: '{epi_seq}' not found in sequence!")
                continue

            # Core
            bc_ov = bc_rk = 0.0, 999
            for ep in core_epi:
                ov = overlap_fraction(ep.start, ep.end, ks, ke)
                if ov > bc_ov[0]:
                    bc_ov = (ov, ep.rank)
            if bc_ov[0] >= 0.50:
                core_det += 1; p_core += 1
                if bc_ov[1] <= 5: core_t5 += 1; p_c5 += 1
                if bc_ov[1] <= 10: core_t10 += 1

            # Bio
            bb_ov = bb_rk = 0.0, 999
            for h in bio_hits:
                ov = overlap_fraction(h.start, h.end, ks, ke)
                if ov > bb_ov[0]:
                    bb_ov = (ov, h.rank)
            if bb_ov[0] >= 0.50:
                bio_det += 1; p_bio += 1
                if bb_ov[1] <= 5: bio_t5 += 1; p_b5 += 1
                if bb_ov[1] <= 10: bio_t10 += 1
            else:
                missed_bio.append((prot.name, epi_seq, bb_ov[0]))

            if verbose:
                sc = "DETECTED" if bc_ov[0] >= 0.50 else "missed"
                sb = "DETECTED" if bb_ov[0] >= 0.50 else "missed"
                print(f"       Epitope: {epi_seq[:35]:<35s}  pos {ks}-{ke}")
                print(f"         Core: {sc} ({bc_ov[0]:.0%})   "
                      f"Bio: {sb} ({bb_ov[0]:.0%})")

        protein_results.append({
            "name": prot.name, "n": len(prot.known_epitopes),
            "cd": p_core, "bd": p_bio, "c5": p_c5, "b5": p_b5,
        })

    # ---- Summary ----
    print()
    print("=" * 100)
    print("  100-PROTEIN BENCHMARK SUMMARY")
    print("=" * 100)
    print()
    print(f"  {'#':<4} {'Protein':<35s} {'Known':>5} {'Core':>6} "
          f"{'Bio':>6} {'C-T5':>5} {'B-T5':>5}")
    print("  " + "-" * 90)
    for i, r in enumerate(protein_results, 1):
        print(f"  {i:<4} {r['name']:<35s} {r['n']:>5} "
              f"{r['cd']:>6} {r['bd']:>6} {r['c5']:>5} {r['b5']:>5}")
    print("  " + "-" * 90)
    print(f"  {'':4} {'TOTAL':<35s} {total_known:>5} "
          f"{core_det:>6} {bio_det:>6} {core_t5:>5} {bio_t5:>5}")
    print()

    def pct(a, b): return f"{a}/{b} ({a/b*100:.1f}%)" if b else "N/A"
    print(f"  Core sensitivity:   {pct(core_det, total_known)}")
    print(f"  Bio  sensitivity:   {pct(bio_det, total_known)}")
    print(f"  Core Top-5 rate:    {pct(core_t5, total_known)}")
    print(f"  Bio  Top-5 rate:    {pct(bio_t5, total_known)}")
    print(f"  Core Top-10 rate:   {pct(core_t10, total_known)}")
    print(f"  Bio  Top-10 rate:   {pct(bio_t10, total_known)}")
    print()

    if missed_bio:
        print(f"  Bio missed epitopes ({len(missed_bio)} total):")
        for name, epi, ov in missed_bio[:20]:
            print(f"    {name:30s}  {epi[:30]:30s}  overlap={ov:.0%}")
        if len(missed_bio) > 20:
            print(f"    ... and {len(missed_bio) - 20} more")

    print("=" * 100)
    return bio_det, core_det, total_known


